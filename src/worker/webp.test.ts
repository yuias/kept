import { describe, expect, it } from 'vitest'
import { isWebp } from './webp'

const MINIMAL_WEBP = new Uint8Array([
  0x52, 0x49, 0x46, 0x46, 0x1a, 0x00, 0x00, 0x00, 0x57, 0x45, 0x42, 0x50, 0x56, 0x50, 0x38, 0x20,
  0x0e, 0x00, 0x00, 0x00, 0x10, 0x01, 0x00, 0x9d, 0x01, 0x2a, 0x01, 0x00, 0x01, 0x00, 0x02, 0x00,
  0x34, 0x25, 0xa4, 0x00, 0x03, 0x70, 0x00, 0xfe, 0xfb, 0xfd, 0x50, 0x00,
])

describe('isWebp', () => {
  it('accepts bytes with the RIFF/WEBP magic header', () => {
    expect(isWebp(MINIMAL_WEBP)).toBe(true)
  })

  it('rejects PNG bytes', () => {
    const png = new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0, 0, 0, 0])
    expect(isWebp(png)).toBe(false)
  })

  it('rejects a RIFF container that is not WEBP', () => {
    const wav = new Uint8Array([0x52, 0x49, 0x46, 0x46, 0, 0, 0, 0, 0x57, 0x41, 0x56, 0x45])
    expect(isWebp(wav)).toBe(false)
  })

  it('rejects bytes shorter than the header', () => {
    expect(isWebp(new Uint8Array([0x52, 0x49, 0x46, 0x46]))).toBe(false)
  })
})
